export const getAugmentById = (id: string): Augment | undefined => {
  const allAugments = [...tier1Augments, ...tier2Augments, ...tier3Augments];
  return allAugments.find((augment) => augment.id === id);
};

export const getAugmentsByTier = (tier: AugmentTier): Augment[] => {
  switch (tier) {
    case "silver":
      return tier1Augments;
    case "gold":
      return tier2Augments;
    case "prismatic":
      return tier3Augments;
  }
};

export const getAugment = (idOrName: string): Augment | undefined => {
  const allAugments = [...tier1Augments, ...tier2Augments, ...tier3Augments];
  const search = idOrName.toLowerCase();
  return allAugments.find(
    (augment) =>
      augment.id.toLowerCase() === search ||
      augment.name.toLowerCase() === search
  );
};

