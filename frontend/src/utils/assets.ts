/**
 * Resolves a name to its correct key using normalization and synonym map.
 */
function resolveKey(name: string, assets: Record<string, any>): string {
  const normalized = normalizeName(name);

  // 1. Direct match
  if (normalized in assets) return normalized;

  // 2. Synonym match
  if (normalized in synonymMap) {
    const mapped = synonymMap[normalized];
    if (mapped in assets) return mapped;
  }

  // 3. Try removing non-alphanumeric characters (simplified match)
  // This helps with cases like "Kai'Sa" vs "KaiSa" if not in map
  const simplified = normalized.replace(/[^a-zA-Z0-9]/g, "");
  const assetKeys = Object.keys(assets);
  const foundKey = assetKeys.find(key => key.replace(/[^a-zA-Z0-9]/g, "") === simplified);

  if (foundKey) return foundKey;

  return normalized; // Return original if no match found
}

/**
 * Resolves a champion name to its canonical form using synonyms and normalization.
 * @param name - The name to resolve
 * @returns The canonical champion name
 */
export function resolveChampionName(name: string): string {
  return resolveKey(name, championAssets);
}

/**
 * Obtiene la imagen de un campeón a partir de una ruta de archivo o nombre
 * @param imagePath - Ruta como "/src/assets/Champions/Braum.png.webp" o nombre como "Braum"
 * @returns La URL de la imagen o una imagen por defecto
 */
export function getChampionImage(imagePath: string): string {
  // Si es una ruta completa, extraer el nombre del campeón
  const match = imagePath.match(/\/([^\/]+)\.(?:png|jpe?g|webp)$/);
  let championName = match ? match[1] : imagePath;

  championName = resolveKey(championName, championAssets);

  const asset = championAssets[championName as keyof typeof championAssets];
  if (!asset) return imagePath;

  return typeof asset === 'string' ? asset : asset.src || imagePath;
}

/**
 * Obtiene la metadata de imagen de un campeón para usar con el componente Image de Astro
 * @param imagePath - Ruta como "/src/assets/Champions/Braum.png.webp" o nombre como "Braum"
 * @returns ImageMetadata para usar con el componente Image de Astro
 */
export function getChampionImageMeta(imagePath: string) {
  const match = imagePath.match(/\/([^\/]+)\.(?:png|jpe?g|webp)$/);
  let championName = match ? match[1] : imagePath;

  championName = resolveKey(championName, championAssets);

  return championAssets[championName as keyof typeof championAssets];
}

/**
 * Obtiene la imagen de un item a partir del nombre
 * @param itemName - Nombre del item como "Infinity Edge"
 * @returns La URL de la imagen o una imagen por defecto
 */
export function getItemImage(itemName: string, set?: string | null): string {
  const assets = getItemAssetMap(set);
  const resolvedName = resolveKey(itemName, assets);
  const asset = assets[resolvedName as keyof typeof assets];

  if (!asset) return "";
  return typeof asset === 'string' ? asset : asset.src || "";
}

/**
 * Obtiene la metadata de imagen de un item para usar con el componente Image de Astro
 * @param itemName - Nombre del item como "Infinity Edge"
 * @returns ImageMetadata para usar con el componente Image de Astro
 */
export function getItemImageMeta(itemName: string, set?: string | null) {
  const assets = getItemAssetMap(set);
  const resolvedName = resolveKey(itemName, assets);
  return assets[resolvedName as keyof typeof assets];
}

/**
 * Verifica si un campeón existe en los assets
 * @param championName - Nombre del campeón
 * @returns True si el campeón existe
 */
export function hasChampion(championName: string): boolean {
  const resolvedName = resolveKey(championName, championAssets);
  return resolvedName in championAssets;
}

/**
 * Verifica si un item existe en los assets
 * @param itemName - Nombre del item
 * @returns True si el item existe
 */
export function hasItem(itemName: string, set?: string | null): boolean {
  const assets = getItemAssetMap(set);
  const resolvedName = resolveKey(itemName, assets);
  return resolvedName in assets;
}

