/**
 * Obtiene el thumbnail de un campeón con fallback a la resolución de nombres.
 * Usa la misma lógica de resolveKey que assets.ts para manejar sinónimos.
 */
export function getChampionThumb(name: string): any {
  if (!name) return undefined;
  const trimmed = name.trim();

  // Direct match
  if (trimmed in championThumbs) return championThumbs[trimmed];

  // Simplified alphanumeric match
  const simplified = trimmed.replace(/[^a-zA-Z0-9]/g, "");
  const key = Object.keys(championThumbs).find(
    (k) => k.replace(/[^a-zA-Z0-9]/g, "") === simplified
  );
  return key ? championThumbs[key] : undefined;
}
